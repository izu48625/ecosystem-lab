'use strict';
const assert=require('node:assert/strict'),{Lab,BRAIN_SIZE,SPECIES}=require('../src/sim-core.js');
const base={seed:20560001,green:100,red:20,blue:0,mode:'social'};
for(const model of ['ecoMate','ecoMateWide','ecoMateHunger','ecoVigilance']){
 const l=new Lab({...base,socialEvolution:model});
 l.aiLog=()=>{};
 assert.equal(l.entities.find(e=>e.type==='g').genome.length,BRAIN_SIZE);
 l.run(10,.08);
 assert.ok(l.stats.births.g>0);
 assert.ok(l.stats.ai.highestGeneration>0);
 assert.ok(l.entities.filter(e=>e.type==='g').every(e=>e.ecoFood>=0&&e.ecoDays>=0));
 console.log('✓ '+model+' live body, ecology, genetic mating and heredity');
}
const l=new Lab({...base,socialEvolution:'ecoMate',socialNoMutation:true});
const parent={genome:new Array(BRAIN_SIZE).fill(-2)};
const mate={genome:new Array(BRAIN_SIZE).fill(2)};
const child=l.mutateBrain(parent,mate);
assert.ok(child.includes(-2)&&child.includes(2),'sexual recombination of two heritable brains');
assert.ok(child.every(w=>w===2||w===-2),'mutation-off has no new alleles');
assert.equal(l.stats.ai.mutatedOffspring,0);
const body=l.entities.filter(e=>e.type==='g')[0];
const poor={...body,ecoDays:9,ecoFood:0,ecoEscapes:0,ecoHits:2,children:0,energy:45};
const success={...body,ecoDays:9,ecoFood:300,ecoEscapes:3,ecoHits:0,children:3,energy:80};
assert.ok(l.ecologicalMateScore(success)>l.ecologicalMateScore(poor));
const noGroup=new Lab({...base,socialEvolution:'ecoVigilance',socialEnabled:false});noGroup.aiLog=()=>{};
let calls=0;
const original=noGroup.socialSharedPredator;
noGroup.socialSharedPredator=function(...args){calls++;return original.apply(this,args)};
noGroup.run(10,.08);
assert.equal(calls,0,'disabling social signalling must disable danger sharing');
const warning=new Lab({...base,socialEvolution:'ecoVigilance'});warning.aiLog=()=>{};
let successAlerts=0;
const orig=warning.socialSharedPredator;
warning.socialSharedPredator=function(...args){const value=orig.apply(this,args);if(value)successAlerts++;return value};
warning.run(12,.08);
assert.ok(successAlerts>0,'real neighbor relays predator sightings');
assert.equal(SPECIES.r.speed,1.15);
assert.equal(SPECIES.r.attack,20);
console.log(JSON.stringify({successfulRelays:successAlerts,noGroupRelays:calls,mutationOffRecombined:true}));
